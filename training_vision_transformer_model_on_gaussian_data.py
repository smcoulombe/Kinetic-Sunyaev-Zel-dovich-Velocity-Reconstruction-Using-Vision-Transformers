for epoch in range(start_epoch, MAX_EPOCHS):
    stage = CURRICULUM_STAGES[stage_idx]

    # --- stage transition: runs once, the epoch right after stage_idx changed ---
    # (triggered below by "epochs_since_improvement >= PATIENCE" incrementing
    # stage_idx at the end of the previous iteration). Snapshots + checkpoints
    # the just-finished stage, then rebuilds the train/val mixture for the new
    # one and resets the early-stopping counters.
    if stage_idx != prev_stage_idx:
        if prev_stage_idx is not None:
            stage_end_ckpt = os.path.join(DATA_DIR, f"model_weights_{SNAPSHOT_TAG}_stage{prev_stage_idx+1}_end.pt")
            torch.save(model.state_dict(), stage_end_ckpt)
            print(f"Saved end-of-stage-{prev_stage_idx+1} checkpoint to {stage_end_ckpt}")

