# Simple edge-padded box-car smoother, applied to power spectra before
# synfast so the synthetic test realization matches the smoothing already
# baked into the training realizations.
def moving_average(y, window):
    if window <= 1:
        return y
    kernel = np.ones(window) / window
    pad = window // 2
    y_padded = np.pad(y, pad, mode="edge")
    smoothed = np.convolve(y_padded, kernel, mode="same")
    return smoothed[pad:pad + len(y)]

