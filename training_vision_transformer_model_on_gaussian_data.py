"""
Binned multi-shell ViT training pipeline.

Reconstructs v0, v1, v2 (3 output channels) from Tnoise = T + eps*noise plus
tau0, tau1, tau2 (4 input channels), where T = sum_i(v_i * tau_i) is the
already-generated integrated signal across all 3 bins.

Structural decisions this script implements (see conversation for full
reasoning behind each):
  1. 4 input channels [Tnoise, tau0, tau1, tau2], 3 output channels [v0,v1,v2]
  2. One extra test realization (seed=32), generated the same way as the
     32 train/val realizations, saved separately and never used in training
  3. Loss weights: pooled across v0-2 (already computed, binned_loss_scale.npz)
  4. v, tau, noise, T cached once (eps-agnostic); Tnoise composed on the fly
  5. One Mollweide + one patch-comparison plot set per bin (3 sets) per snapshot
  6. SNAPSHOT_TAG = "binned" (no single shell_nr anymore)
  7. Loss averaged across the 3 output channels (not summed)
  8. Same EPS_LIST / curriculum staging logic as before, built parametrically
  9. NSIDE_PATCH = 256 (matches binned_loss_scale.npz)
  10. 90/10 train/val split, kept as an adjustable parameter
  11. Patch cache: 4 stacked files (tau_stack, v_target_stack, noise, T),
      same resumable/chunked build approach, sequential (not parallelized)
  12. Training starts from scratch; resumable if interrupted
  13. Same hyperparameters as before, kept as easily-editable constants
  14. Same model architecture (embed_dim=64, depth=4, n_heads=4, mlp_ratio=4)
  15. n_spec_bins / spec_loss_eps loaded from binned_loss_scale.npz
  16. Patch-cache build is sequential (not parallelized)

  NEW CHANGES:
  1. slower curriculum with more intermediate stages and a 2 tier epsilon retirement process
  2. patience raised and min delta lowered

  NEW CHANGES - bigger model (embed 64-128, depth 4-5)
"""

