RESUME_STATE_FILE = os.path.join(DATA_DIR, f"resume_state_{SNAPSHOT_TAG}.npz")

def save_resume_state(next_epoch, stage_idx, prev_stage_idx, epochs_since_improvement, best_val_loss,
                       global_best_val_loss, global_best_epoch, eps_seen_so_far, stage_log):
    # Persist everything needed to resume training exactly where it left
    # off after a restart: epoch/stage counters, early-stopping counters,
    # best-loss bookkeeping, which eps values have been introduced so far,
    # and the stage-transition log. None values are stored as -1 since npz
    # can't hold None.
    np.savez(RESUME_STATE_FILE,
             next_epoch=next_epoch,
             stage_idx=stage_idx,
             prev_stage_idx=prev_stage_idx if prev_stage_idx is not None else -1,
             epochs_since_improvement=epochs_since_improvement,
             best_val_loss=best_val_loss,
             global_best_val_loss=global_best_val_loss,
             global_best_epoch=global_best_epoch if global_best_epoch is not None else -1,
             eps_seen_so_far=np.array(sorted(eps_seen_so_far)),
             stage_log=np.array(stage_log, dtype=object))

def load_resume_state():
    if not os.path.exists(RESUME_STATE_FILE):
        return None
    d = np.load(RESUME_STATE_FILE, allow_pickle=True)
    gbe = int(d["global_best_epoch"])
    psi = int(d["prev_stage_idx"]) if "prev_stage_idx" in d else int(d["stage_idx"])
    return {
        "next_epoch": int(d["next_epoch"]),
        "stage_idx": int(d["stage_idx"]),
        "prev_stage_idx": None if psi == -1 else psi,
        "epochs_since_improvement": int(d["epochs_since_improvement"]),
        "best_val_loss": float(d["best_val_loss"]),
        "global_best_val_loss": float(d["global_best_val_loss"]),
        "global_best_epoch": None if gbe == -1 else gbe,
        "eps_seen_so_far": set(d["eps_seen_so_far"].tolist()),
        "stage_log": list(d["stage_log"]),
    }

