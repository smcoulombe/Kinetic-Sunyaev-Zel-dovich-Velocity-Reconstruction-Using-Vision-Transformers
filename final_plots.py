def bin_cl_weighted(ell_in, cl_in, bin_edges, weights):
    binned = np.full(len(bin_edges) - 1, np.nan)
    for i in range(len(bin_edges) - 1):
        mask = (ell_in >= bin_edges[i]) & (ell_in < bin_edges[i + 1])
        if mask.sum() == 0:
            continue
        w = weights[mask]
        binned[i] = np.sum(w * cl_in[mask]) / np.sum(w)
    return binned

