def _safe(label):
    return label.replace(" ", "_").replace("/", "_")

def precompute_face_indices(nside):
    npix = hp.nside2npix(nside)
    ipix = np.arange(npix, dtype=np.int32)
    x, y, f = hp.pix2xyf(nside, ipix, nest=True)
    face_idx = {}
    for face_id in range(12):
        mask = f == face_id
        face_idx[face_id] = (ipix[mask].astype(np.int32), x[mask].astype(np.int32), y[mask].astype(np.int32))
    return face_idx

def get_face_2d(map_nest, nside, face_id, face_idx):
    ipix_f, x_f, y_f = face_idx[face_id]
    face_img = np.full((nside, nside), np.nan, dtype=map_nest.dtype)
    face_img[y_f, x_f] = map_nest[ipix_f]
    return face_img

def extract_patch(map_ring, face_id=PATCH_FACE, row=PATCH_ROW, col=PATCH_COL):
    map_nest = hp.reorder(map_ring, r2n=True)
    face_img = get_face_2d(map_nest, NSIDE_MAP, face_id, FACE_IDX)
    return face_img[row*NSIDE_PATCH:(row+1)*NSIDE_PATCH, col*NSIDE_PATCH:(col+1)*NSIDE_PATCH]

def make_patch_mask(nside_map, face_id, row, col, nside_patch, face_idx):
    npix = hp.nside2npix(nside_map)
    mask = np.zeros(npix, dtype=bool)
    ipix_f, x_f, y_f = face_idx[face_id]
    row_mask = (y_f >= row * nside_patch) & (y_f < (row + 1) * nside_patch)
    col_mask = (x_f >= col * nside_patch) & (x_f < (col + 1) * nside_patch)
    patch_mask = row_mask & col_mask
    mask[ipix_f[patch_mask]] = True
    return mask

def with_patch_highlighted(map_ring, patch_mask_nest):
    map_nest = hp.reorder(map_ring, r2n=True).copy()
    map_nest[patch_mask_nest] = np.nan
    return hp.reorder(map_nest, n2r=True)

def add_col_axes(fig, fig_w_in, fig_h_in, col):
    """Create (mollweide, patch, colorbar) axes for one column at exact inch positions."""
    x0_in = SIDE_MARGIN_IN + col * (COL_WIDTH_IN + COL_GAP_IN)

    moll_y1_in = fig_h_in - TOP_MARGIN_IN
    moll_y0_in = moll_y1_in - MOLL_HEIGHT_IN
    patch_y1_in = moll_y0_in - GAP_IN
    patch_y0_in = patch_y1_in - PATCH_HEIGHT_IN
    cbar_y1_in = patch_y0_in - CBAR_PAD_IN
    cbar_y0_in = cbar_y1_in - CBAR_HEIGHT_IN

    def to_frac(x_in, y_in, w_in, h_in):
        return [x_in / fig_w_in, y_in / fig_h_in, w_in / fig_w_in, h_in / fig_h_in]

    moll_ax  = fig.add_axes(to_frac(x0_in, moll_y0_in, COL_WIDTH_IN, MOLL_HEIGHT_IN))
    patch_ax = fig.add_axes(to_frac(x0_in, patch_y0_in, COL_WIDTH_IN, PATCH_HEIGHT_IN))
    cbar_ax  = fig.add_axes(to_frac(x0_in, cbar_y0_in, COL_WIDTH_IN, CBAR_HEIGHT_IN))
    return moll_ax, patch_ax, cbar_ax

def plot_mollweide(moll_ax, data, title, vmax, cmap):
    """Draw into moll_ax, restoring its exact position afterward (mollview repositions
    axes internally on call)."""
    pos = moll_ax.get_position()
    plt.axes(moll_ax)
    hp.mollview(data, hold=True, title=title, min=-vmax, max=vmax, cmap=cmap,
                badcolor="grey", cbar=False)
    moll_ax.set_position(pos)

